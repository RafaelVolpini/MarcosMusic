const today = new Date();

const toIsoDate = (date: Date) => date.toISOString().split('T')[0] ?? '';

const shiftDate = (days: number) => {
  const date = new Date(today);
  date.setDate(date.getDate() + days);
  return toIsoDate(date);
};

